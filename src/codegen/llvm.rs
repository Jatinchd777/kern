use std::collections::HashMap;
use std::fmt::Write as _;

use crate::hir::{
    Block, ElseBranch, EnumId, Expr, ExprKind, Function, FunctionId, LocalId, MatchPattern,
    PrintItem, Stmt, StmtKind,
};
use crate::parser::ast::BinaryOp;
use crate::semantic::types::Type;

/// Generates textual LLVM IR. The CLI feeds this IR to Clang, which performs
/// LLVM optimization and produces the native executable.
pub fn generate(program: &crate::hir::Program) -> Result<String, String> {
    let mut generator = Generator {
        program,
        strings: Vec::new(),
        string_ids: HashMap::new(),
    };
    generator.generate_module()
}

struct Generator<'a> {
    program: &'a crate::hir::Program,
    strings: Vec<Vec<u8>>,
    string_ids: HashMap<String, usize>,
}

struct LocalSlot {
    name: String,
    llvm_type: String,
    ty: Type,
}

struct LoopTarget {
    break_label: String,
    continue_label: String,
}

struct FunctionCtx {
    lines: Vec<String>,
    next_temp: u32,
    next_label: u32,
    current_label: String,
    terminated: bool,
    locals: Vec<LocalSlot>,
    loop_stack: Vec<LoopTarget>,
    is_main: bool,
    llvm_return_type: String,
}

impl FunctionCtx {
    fn new(is_main: bool, llvm_return_type: String) -> Self {
        Self {
            lines: Vec::new(),
            next_temp: 0,
            next_label: 0,
            current_label: "entry".to_string(),
            terminated: false,
            locals: Vec::new(),
            loop_stack: Vec::new(),
            is_main,
            llvm_return_type,
        }
    }

    fn temp(&mut self) -> String {
        let name = format!("%t{}", self.next_temp);
        self.next_temp += 1;
        name
    }

    fn label(&mut self) -> String {
        let name = format!("bb{}", self.next_label);
        self.next_label += 1;
        name
    }

    fn emit(&mut self, instruction: String) {
        debug_assert!(!self.terminated, "instruction emitted after terminator");
        if !self.terminated {
            self.lines.push(format!("  {instruction}"));
        }
    }

    fn terminate(&mut self, instruction: String) {
        if !self.terminated {
            self.lines.push(format!("  {instruction}"));
            self.terminated = true;
        }
    }

    fn start_label(&mut self, label: &str) {
        if !self.terminated {
            self.lines.push(format!("  br label %{label}"));
        }
        self.lines.push(format!("{label}:"));
        self.current_label = label.to_string();
        self.terminated = false;
    }

    fn local(&self, id: LocalId) -> Result<&LocalSlot, String> {
        self.locals
            .get(id.0 as usize)
            .ok_or_else(|| format!("internal codegen error: local {} was not allocated", id.0))
    }
}

impl<'a> Generator<'a> {
    fn generate_module(&mut self) -> Result<String, String> {
        let mut module = String::new();
        let _ = writeln!(module, "; Generated by Kern");
        let _ = writeln!(module, "declare i32 @printf(ptr, ...)");
        let _ = writeln!(module, "declare i32 @putchar(i32)");
        let _ = writeln!(module, "declare i32 @scanf(ptr, ...)");
        let _ = writeln!(module);
        module.push_str(&binary_print_helper());
        let _ = writeln!(module);

        module.push_str(&self.emit_struct_types()?);

        for index in 0..self.program.functions.len() {
            let function = self.program.functions[index].clone();
            module.push_str(&self.generate_function(&function)?);
        }

        module.push_str(&self.emit_globals());
        Ok(module)
    }

    fn emit_struct_types(&self) -> Result<String, String> {
        let mut output = String::new();
        for struct_def in &self.program.structs {
            let mut fields = Vec::new();
            for field in &struct_def.fields {
                let ty = self.llvm_type(&field.ty)?;
                if ty == "void" {
                    return Err(format!(
                        "internal codegen error: struct `{}` has a field of unit type",
                        struct_def.name
                    ));
                }
                fields.push(ty);
            }
            let _ = writeln!(
                output,
                "%kern.{} = type {{ {} }}",
                struct_def.name,
                fields.join(", ")
            );
        }
        if !self.program.structs.is_empty() {
            let _ = writeln!(output);
        }
        Ok(output)
    }

    fn generate_function(&mut self, function: &Function) -> Result<String, String> {
        let is_main = function.name == "main";
        let llvm_return_type = if is_main {
            "i32".to_string()
        } else {
            self.llvm_type(&function.return_type)?
        };

        let mut params = Vec::new();
        if !is_main {
            for param in &function.params {
                let ty = self.llvm_type(&param.ty)?;
                if ty == "void" {
                    return Err(format!(
                        "internal codegen error: parameter `{}` has unit type",
                        param.name
                    ));
                }
                params.push(format!("{ty} %p{}", param.local.0));
            }
        }

        let mut ctx = FunctionCtx::new(is_main, llvm_return_type.clone());

        for (index, ty) in function.local_types.iter().enumerate() {
            let llvm_type = self.llvm_type(ty)?;
            if llvm_type == "void" {
                return Err(format!(
                    "internal codegen error: local {index} in function `{}` has unit type",
                    function.name
                ));
            }
            ctx.locals.push(LocalSlot {
                name: format!("%l{index}"),
                llvm_type,
                ty: ty.clone(),
            });
        }

        let symbol = self.function_symbol(function);
        let mut output = String::new();
        let _ = writeln!(
            output,
            "define {} {}({}) {{",
            llvm_return_type,
            symbol,
            params.join(", ")
        );
        let _ = writeln!(output, "entry:");
        for slot in &ctx.locals {
            let _ = writeln!(output, "  {} = alloca {}", slot.name, slot.llvm_type);
        }
        for param in &function.params {
            let ty = self.llvm_type(&param.ty)?;
            let _ = writeln!(
                output,
                "  store {} %p{}, ptr %l{}",
                ty, param.local.0, param.local.0
            );
        }

        self.gen_block(&mut ctx, &function.body)?;

        if !ctx.terminated {
            if is_main {
                ctx.terminate("ret i32 0".to_string());
            } else if function.return_type.is_unit() {
                ctx.terminate("ret void".to_string());
            } else {
                ctx.terminate("unreachable".to_string());
            }
        }

        for line in &ctx.lines {
            let _ = writeln!(output, "{line}");
        }
        let _ = writeln!(output, "}}");
        let _ = writeln!(output);
        Ok(output)
    }

    fn function_symbol(&self, function: &Function) -> String {
        if function.name == "main" {
            "@main".to_string()
        } else {
            format!("@kern.{}", function.name)
        }
    }

    fn function_symbol_by_id(&self, id: FunctionId) -> Result<String, String> {
        let function = self
            .program
            .functions
            .get(id.0)
            .ok_or_else(|| format!("internal codegen error: unknown function id {}", id.0))?;
        Ok(self.function_symbol(function))
    }

    fn llvm_type(&self, ty: &Type) -> Result<String, String> {
        Ok(match ty {
            Type::Unit => "void".to_string(),
            Type::Bool => "i1".to_string(),
            Type::Char => "i32".to_string(),
            Type::I8 => "i8".to_string(),
            Type::I16 => "i16".to_string(),
            Type::I32 => "i32".to_string(),
            Type::I64 => "i64".to_string(),
            Type::I128 => "i128".to_string(),
            Type::Isize => "i64".to_string(),
            Type::U8 => "i8".to_string(),
            Type::U16 => "i16".to_string(),
            Type::U32 => "i32".to_string(),
            Type::U64 => "i64".to_string(),
            Type::U128 => "i128".to_string(),
            Type::Usize => "i64".to_string(),
            Type::F32 => "float".to_string(),
            Type::F64 => "double".to_string(),
            Type::String => "ptr".to_string(),
            Type::Struct(id) => {
                let struct_def =
                    self.program.structs.get(id.0).ok_or_else(|| {
                        format!("internal codegen error: unknown struct id {}", id.0)
                    })?;
                format!("%kern.{}", struct_def.name)
            }
            Type::Enum(_) => "i32".to_string(),
            Type::Error => {
                return Err("internal codegen error: attempted to lower an error type".to_string());
            }
        })
    }

    fn add_string(&mut self, value: &str) -> String {
        if let Some(index) = self.string_ids.get(value) {
            return format!("@.kern.str.{index}");
        }
        let index = self.strings.len();
        self.strings.push(value.as_bytes().to_vec());
        self.string_ids.insert(value.to_string(), index);
        format!("@.kern.str.{index}")
    }

    fn global_ptr(&self, ctx: &mut FunctionCtx, global: &str, length: usize) -> String {
        let temp = ctx.temp();
        ctx.emit(format!(
            "{temp} = getelementptr inbounds [{length} x i8], ptr {global}, i64 0, i64 0"
        ));
        temp
    }

    fn gen_block(&mut self, ctx: &mut FunctionCtx, block: &Block) -> Result<(), String> {
        for statement in &block.statements {
            if ctx.terminated {
                break;
            }
            self.gen_stmt(ctx, statement)?;
        }
        Ok(())
    }

    fn gen_stmt(&mut self, ctx: &mut FunctionCtx, statement: &Stmt) -> Result<(), String> {
        match &statement.kind {
            StmtKind::Let {
                local, ty, value, ..
            } => {
                if let Some(value) = value {
                    let value = self.gen_expr(ctx, value)?;
                    let llvm_type = self.llvm_type(ty)?;
                    let slot = ctx.local(*local)?;
                    ctx.emit(format!("store {} {}, ptr {}", llvm_type, value, slot.name));
                }
            }
            StmtKind::Assign { local, value } => {
                let llvm_type = self.llvm_type(&value.ty)?;
                let value = self.gen_expr(ctx, value)?;
                let slot = ctx.local(*local)?;
                ctx.emit(format!("store {} {}, ptr {}", llvm_type, value, slot.name));
            }
            StmtKind::Expr(expr) => {
                let _ = self.gen_expr(ctx, expr)?;
            }
            StmtKind::Print { items, newline } => {
                self.gen_print(ctx, items, *newline)?;
            }
            StmtKind::Cin(locals) => {
                for local in locals {
                    self.gen_cin(ctx, *local)?;
                }
            }
            StmtKind::If {
                condition,
                then_block,
                else_branch,
            } => {
                let condition = self.gen_expr(ctx, condition)?;
                let then_label = ctx.label();
                let else_label = ctx.label();
                let merge_label = ctx.label();
                ctx.terminate(format!(
                    "br i1 {condition}, label %{then_label}, label %{else_label}"
                ));

                ctx.start_label(&then_label);
                self.gen_block(ctx, then_block)?;
                if !ctx.terminated {
                    ctx.terminate(format!("br label %{merge_label}"));
                }

                ctx.start_label(&else_label);
                match else_branch {
                    Some(ElseBranch::Block(block)) => {
                        self.gen_block(ctx, block)?;
                    }
                    Some(ElseBranch::If(statement)) => {
                        self.gen_stmt(ctx, statement)?;
                    }
                    None => {}
                }
                if !ctx.terminated {
                    ctx.terminate(format!("br label %{merge_label}"));
                }

                ctx.start_label(&merge_label);
            }
            StmtKind::While { condition, body } => {
                let header_label = ctx.label();
                let body_label = ctx.label();
                let exit_label = ctx.label();
                ctx.terminate(format!("br label %{header_label}"));

                ctx.start_label(&header_label);
                let condition = self.gen_expr(ctx, condition)?;
                ctx.terminate(format!(
                    "br i1 {condition}, label %{body_label}, label %{exit_label}"
                ));

                ctx.start_label(&body_label);
                ctx.loop_stack.push(LoopTarget {
                    break_label: exit_label.clone(),
                    continue_label: header_label.clone(),
                });
                self.gen_block(ctx, body)?;
                ctx.loop_stack.pop();
                if !ctx.terminated {
                    ctx.terminate(format!("br label %{header_label}"));
                }

                ctx.start_label(&exit_label);
            }
            StmtKind::Loop { body } => {
                let header_label = ctx.label();
                let exit_label = ctx.label();
                ctx.terminate(format!("br label %{header_label}"));
                ctx.start_label(&header_label);
                ctx.loop_stack.push(LoopTarget {
                    break_label: exit_label.clone(),
                    continue_label: header_label.clone(),
                });
                self.gen_block(ctx, body)?;
                ctx.loop_stack.pop();
                if !ctx.terminated {
                    ctx.terminate(format!("br label %{header_label}"));
                }
                ctx.start_label(&exit_label);
            }
            StmtKind::For {
                init,
                condition,
                update,
                body,
            } => {
                if let Some(init) = init {
                    self.gen_stmt(ctx, init)?;
                }
                let header_label = ctx.label();
                let body_label = ctx.label();
                let update_label = ctx.label();
                let exit_label = ctx.label();
                ctx.terminate(format!("br label %{header_label}"));

                ctx.start_label(&header_label);
                if let Some(condition) = condition {
                    let condition = self.gen_expr(ctx, condition)?;
                    ctx.terminate(format!(
                        "br i1 {condition}, label %{body_label}, label %{exit_label}"
                    ));
                } else {
                    ctx.terminate(format!("br label %{body_label}"));
                }

                ctx.start_label(&body_label);
                ctx.loop_stack.push(LoopTarget {
                    break_label: exit_label.clone(),
                    continue_label: update_label.clone(),
                });
                self.gen_block(ctx, body)?;
                ctx.loop_stack.pop();
                if !ctx.terminated {
                    ctx.terminate(format!("br label %{update_label}"));
                }

                ctx.start_label(&update_label);
                if let Some(update) = update {
                    self.gen_stmt(ctx, update)?;
                }
                if !ctx.terminated {
                    ctx.terminate(format!("br label %{header_label}"));
                }

                ctx.start_label(&exit_label);
            }
            StmtKind::Break => {
                let target = ctx
                    .loop_stack
                    .last()
                    .ok_or_else(|| "internal codegen error: break outside loop".to_string())?;
                let label = target.break_label.clone();
                ctx.terminate(format!("br label %{label}"));
            }
            StmtKind::Continue => {
                let target = ctx
                    .loop_stack
                    .last()
                    .ok_or_else(|| "internal codegen error: continue outside loop".to_string())?;
                let label = target.continue_label.clone();
                ctx.terminate(format!("br label %{label}"));
            }
            StmtKind::Return(value) => {
                self.gen_return(ctx, value.as_ref())?;
            }
            StmtKind::Block(block) => {
                self.gen_block(ctx, block)?;
            }
            StmtKind::Match { scrutinee, arms } => {
                self.gen_match(ctx, scrutinee, arms)?;
            }
        }
        Ok(())
    }

    fn gen_return(&mut self, ctx: &mut FunctionCtx, value: Option<&Expr>) -> Result<(), String> {
        if ctx.is_main {
            match value {
                Some(value) => {
                    let value = self.gen_expr(ctx, value)?;
                    ctx.terminate(format!("ret i32 {value}"));
                }
                None => ctx.terminate("ret i32 0".to_string()),
            }
            return Ok(());
        }

        match value {
            Some(value) => {
                let value = self.gen_expr(ctx, value)?;
                if ctx.llvm_return_type == "void" {
                    ctx.terminate("ret void".to_string());
                } else {
                    ctx.terminate(format!("ret {} {}", ctx.llvm_return_type, value));
                }
            }
            None => {
                if ctx.llvm_return_type == "void" {
                    ctx.terminate("ret void".to_string());
                } else {
                    ctx.terminate("unreachable".to_string());
                }
            }
        }
        Ok(())
    }

    fn gen_match(
        &mut self,
        ctx: &mut FunctionCtx,
        scrutinee: &Expr,
        arms: &[crate::hir::MatchArm],
    ) -> Result<(), String> {
        let value = self.gen_expr(ctx, scrutinee)?;
        let enum_id = match scrutinee.ty {
            Type::Enum(id) => id,
            _ => {
                return Err("internal codegen error: match scrutinee is not an enum".to_string());
            }
        };

        let merge_label = ctx.label();
        let arm_labels: Vec<String> = arms.iter().map(|_| ctx.label()).collect();
        let wildcard_index = arms
            .iter()
            .position(|arm| matches!(arm.pattern, MatchPattern::Wildcard));
        let default_label = wildcard_index
            .map(|index| arm_labels[index].clone())
            .unwrap_or_else(|| ctx.label());

        let mut cases = String::new();
        for (index, arm) in arms.iter().enumerate() {
            if let MatchPattern::Variant {
                enum_id: pattern_enum,
                variant,
            } = arm.pattern
            {
                if pattern_enum != enum_id {
                    return Err(
                        "internal codegen error: match pattern belongs to a different enum"
                            .to_string(),
                    );
                }
                let tag = self.enum_variant_tag(enum_id, variant)?;
                let _ = writeln!(cases, "    i32 {tag}, label %{}", arm_labels[index]);
            }
        }
        ctx.terminate(format!(
            "switch i32 {value}, label %{default_label} [\n{cases}  ]"
        ));

        for (index, arm) in arms.iter().enumerate() {
            ctx.start_label(&arm_labels[index]);
            self.gen_block(ctx, &arm.body)?;
            if !ctx.terminated {
                ctx.terminate(format!("br label %{merge_label}"));
            }
        }

        if wildcard_index.is_none() {
            ctx.start_label(&default_label);
            ctx.terminate("unreachable".to_string());
        }

        ctx.start_label(&merge_label);
        Ok(())
    }

    fn enum_variant_tag(&self, enum_id: EnumId, variant: usize) -> Result<u32, String> {
        let enum_def = self
            .program
            .enums
            .get(enum_id.0)
            .ok_or_else(|| format!("internal codegen error: unknown enum id {}", enum_id.0))?;
        let variant = enum_def.variants.get(variant).ok_or_else(|| {
            format!(
                "internal codegen error: enum `{}` has no variant {}",
                enum_def.name, variant
            )
        })?;
        Ok(variant.tag)
    }

    fn gen_print(
        &mut self,
        ctx: &mut FunctionCtx,
        items: &[PrintItem],
        newline: bool,
    ) -> Result<(), String> {
        for item in items {
            let separator_before = match item {
                PrintItem::Text {
                    separator_before, ..
                }
                | PrintItem::Value {
                    separator_before, ..
                } => *separator_before,
            };
            if separator_before {
                self.gen_print_string(ctx, " ")?;
            }
            match item {
                PrintItem::Text { value, .. } => self.gen_print_string(ctx, value)?,
                PrintItem::Value { expr, format, .. } => {
                    self.gen_print_value(ctx, expr, *format)?;
                }
            }
        }
        if newline {
            let result = ctx.temp();
            ctx.emit(format!("{result} = call i32 @putchar(i32 10)"));
        }
        Ok(())
    }

    fn gen_print_string(&mut self, ctx: &mut FunctionCtx, value: &str) -> Result<(), String> {
        let global = self.add_string(value);
        let string_ptr = self.global_ptr(ctx, &global, value.len() + 1);
        self.gen_printf(ctx, "%s", format!("ptr {string_ptr}"))
    }

    fn gen_print_value(
        &mut self,
        ctx: &mut FunctionCtx,
        expr: &Expr,
        format: crate::parser::ast::FormatSpec,
    ) -> Result<(), String> {
        let value = self.gen_expr(ctx, expr)?;
        if let Some(crate::parser::ast::Radix::Binary) = format.radix {
            let llvm_type = self.llvm_type(&expr.ty)?;
            let integer = if llvm_type == "i64" {
                value
            } else if expr.ty.is_signed_integer() {
                let extended = ctx.temp();
                ctx.emit(format!("{extended} = sext {llvm_type} {value} to i64"));
                extended
            } else {
                let extended = ctx.temp();
                ctx.emit(format!("{extended} = zext {llvm_type} {value} to i64"));
                extended
            };
            let width = expr.ty.bit_width().unwrap_or(64);
            ctx.emit(format!(
                "call void @kern.print.binary(i64 {integer}, i32 {width})"
            ));
            return Ok(());
        }

        let mut spec = String::from("%");
        if format.zero_pad {
            spec.push('0');
        }
        if let Some(width) = format.width {
            spec.push_str(&width.to_string());
        }

        let argument = match (&expr.ty, format.radix, format.precision) {
            (Type::I8 | Type::I16, Some(radix), _) => {
                spec.push_str(&integer_format(radix, ""));
                let temp = ctx.temp();
                ctx.emit(format!(
                    "{temp} = sext {} {value} to i32",
                    self.llvm_type(&expr.ty)?
                ));
                format!("i32 {temp}")
            }
            (Type::U8 | Type::U16, Some(radix), _) => {
                spec.push_str(&integer_format(radix, ""));
                let temp = ctx.temp();
                ctx.emit(format!(
                    "{temp} = zext {} {value} to i32",
                    self.llvm_type(&expr.ty)?
                ));
                format!("i32 {temp}")
            }
            (Type::I32 | Type::U32, Some(radix), _) => {
                spec.push_str(&integer_format(radix, ""));
                format!("i32 {value}")
            }
            (Type::I64 | Type::U64, Some(radix), _) => {
                spec.push_str(&integer_format(radix, "ll"));
                format!("i64 {value}")
            }
            (Type::Isize | Type::Usize, Some(radix), _) => {
                spec.push_str(&integer_format(radix, "l"));
                format!("i64 {value}")
            }
            (Type::I8 | Type::I16, None, _) => {
                spec.push('d');
                let temp = ctx.temp();
                ctx.emit(format!(
                    "{temp} = sext {} {value} to i32",
                    self.llvm_type(&expr.ty)?
                ));
                format!("i32 {temp}")
            }
            (Type::U8 | Type::U16, None, _) => {
                spec.push('u');
                let temp = ctx.temp();
                ctx.emit(format!(
                    "{temp} = zext {} {value} to i32",
                    self.llvm_type(&expr.ty)?
                ));
                format!("i32 {temp}")
            }
            (Type::I32, None, _) => {
                spec.push('d');
                format!("i32 {value}")
            }
            (Type::U32, None, _) => {
                spec.push('u');
                format!("i32 {value}")
            }
            (Type::I64, None, _) => {
                spec.push_str("lld");
                format!("i64 {value}")
            }
            (Type::U64, None, _) => {
                spec.push_str("llu");
                format!("i64 {value}")
            }
            (Type::Isize, None, _) => {
                spec.push_str("ld");
                format!("i64 {value}")
            }
            (Type::Usize, None, _) => {
                spec.push_str("lu");
                format!("i64 {value}")
            }
            (Type::F32, None, precision) => {
                if let Some(precision) = precision {
                    spec.push_str(&format!(".{precision}f"));
                } else {
                    spec.push('g');
                }
                let temp = ctx.temp();
                ctx.emit(format!("{temp} = fpext float {value} to double"));
                format!("double {temp}")
            }
            (Type::F64, None, precision) => {
                if let Some(precision) = precision {
                    spec.push_str(&format!(".{precision}f"));
                } else {
                    spec.push('g');
                }
                format!("double {value}")
            }
            (Type::Bool, None, None) => {
                spec.push('s');
                let true_ptr = self.global_ptr(ctx, "@.kern.bool.true", 5);
                let false_ptr = self.global_ptr(ctx, "@.kern.bool.false", 6);
                let selected = ctx.temp();
                ctx.emit(format!(
                    "{selected} = select i1 {value}, ptr {true_ptr}, ptr {false_ptr}"
                ));
                format!("ptr {selected}")
            }
            (Type::Char, None, None) => {
                spec.push('c');
                format!("i32 {value}")
            }
            (Type::String, None, None) => {
                spec.push('s');
                format!("ptr {value}")
            }
            (other, _, _) => {
                return Err(format!(
                    "internal codegen error: unsupported formatting for `{other}`"
                ));
            }
        };
        self.gen_printf(ctx, &spec, argument)
    }

    fn gen_printf(
        &mut self,
        ctx: &mut FunctionCtx,
        format: &str,
        argument: String,
    ) -> Result<(), String> {
        let global = self.add_string(format);
        let format_ptr = self.global_ptr(ctx, &global, format.len() + 1);
        let result = ctx.temp();
        ctx.emit(format!(
            "{result} = call i32 (ptr, ...) @printf(ptr {format_ptr}, {argument})"
        ));
        Ok(())
    }

    fn gen_cin(&mut self, ctx: &mut FunctionCtx, local: LocalId) -> Result<(), String> {
        let slot_info = ctx.local(local)?;
        let slot = slot_info.name.clone();
        let ty = slot_info.ty.clone();

        let (format_name, format_length) = match ty {
            Type::I8 => (".kern.scan.i8", 5),
            Type::I16 => (".kern.scan.i16", 4),
            Type::I32 => (".kern.scan.i32", 3),
            Type::I64 => (".kern.scan.i64", 5),
            Type::Isize => (".kern.scan.isize", 4),
            Type::U8 => (".kern.scan.u8", 5),
            Type::U16 => (".kern.scan.u16", 4),
            Type::U32 => (".kern.scan.u32", 3),
            Type::U64 => (".kern.scan.u64", 5),
            Type::Usize => (".kern.scan.usize", 5),
            Type::F32 => (".kern.scan.f32", 3),
            Type::F64 => (".kern.scan.f64", 4),
            Type::Char => (".kern.scan.char", 4),
            Type::Bool => (".kern.scan.i32", 3),
            _ => {
                return Err(format!(
                    "internal codegen error: cannot read type `{ty}` with cin"
                ));
            }
        };
        let format_ptr = self.global_ptr(ctx, &format!("@{format_name}"), format_length);
        let result = ctx.temp();
        if matches!(ty, Type::Bool) {
            let temp = ctx.temp();
            ctx.emit(format!("{temp} = alloca i32"));
            ctx.emit(format!(
                "{result} = call i32 (ptr, ...) @scanf(ptr {format_ptr}, ptr {temp})"
            ));
            let int_value = ctx.temp();
            ctx.emit(format!("{int_value} = load i32, ptr {temp}"));
            let bool_value = ctx.temp();
            ctx.emit(format!("{bool_value} = icmp ne i32 {int_value}, 0"));
            ctx.emit(format!("store i1 {bool_value}, ptr {slot}"));
        } else {
            ctx.emit(format!(
                "{result} = call i32 (ptr, ...) @scanf(ptr {format_ptr}, ptr {slot})"
            ));
        }
        Ok(())
    }

    fn gen_expr(&mut self, ctx: &mut FunctionCtx, expr: &Expr) -> Result<String, String> {
        match &expr.kind {
            ExprKind::Int(value) => Ok(value.to_string()),
            ExprKind::Float(value) => Ok(float_constant(*value, &expr.ty)),
            ExprKind::Bool(value) => Ok(if *value { "1" } else { "0" }.to_string()),
            ExprKind::Char(value) => Ok((*value as u32).to_string()),
            ExprKind::Str(value) => {
                let global = self.add_string(value);
                let ptr = self.global_ptr(ctx, &global, value.len() + 1);
                Ok(ptr)
            }
            ExprKind::Unit => Ok(String::new()),
            ExprKind::Local(id) => {
                let slot_name = ctx.local(*id)?.name.clone();
                let llvm_type = self.llvm_type(&expr.ty)?;
                let temp = ctx.temp();
                ctx.emit(format!("{temp} = load {}, ptr {}", llvm_type, slot_name));
                Ok(temp)
            }
            ExprKind::EnumVariant { enum_id, variant } => {
                Ok(self.enum_variant_tag(*enum_id, *variant)?.to_string())
            }
            ExprKind::Unary { op, expr: operand } => self.gen_unary(ctx, *op, operand, &expr.ty),
            ExprKind::Binary { left, op, right } => {
                if matches!(op, BinaryOp::And | BinaryOp::Or) {
                    return self.gen_logical(ctx, left, *op, right);
                }
                self.gen_binary(ctx, left, *op, right)
            }
            ExprKind::Call { function, args } => {
                let mut lowered_args = Vec::new();
                for arg in args {
                    let value = self.gen_expr(ctx, arg)?;
                    let ty = self.llvm_type(&arg.ty)?;
                    if ty != "void" {
                        lowered_args.push(format!("{ty} {value}"));
                    }
                }
                let symbol = self.function_symbol_by_id(*function)?;
                let return_type = self.llvm_type(&expr.ty)?;
                if return_type == "void" {
                    ctx.emit(format!("call void {}({})", symbol, lowered_args.join(", ")));
                    Ok(String::new())
                } else {
                    let temp = ctx.temp();
                    ctx.emit(format!(
                        "{temp} = call {} {}({})",
                        return_type,
                        symbol,
                        lowered_args.join(", ")
                    ));
                    Ok(temp)
                }
            }
            ExprKind::Field { base, field } => {
                let base_value = self.gen_expr(ctx, base)?;
                let struct_type = self.llvm_type(&base.ty)?;
                let temp = ctx.temp();
                ctx.emit(format!(
                    "{temp} = extractvalue {struct_type} {base_value}, {field}"
                ));
                Ok(temp)
            }
            ExprKind::StructLiteral { struct_id, fields } => {
                let struct_type = self.llvm_type(&Type::Struct(*struct_id))?;
                let mut aggregate = "undef".to_string();
                for (index, field_value) in fields {
                    let field_type = self.llvm_type(&field_value.ty)?;
                    let value = self.gen_expr(ctx, field_value)?;
                    let temp = ctx.temp();
                    ctx.emit(format!(
                        "{temp} = insertvalue {struct_type} {aggregate}, {field_type} {value}, {index}"
                    ));
                    aggregate = temp;
                }
                Ok(aggregate)
            }
        }
    }

    fn gen_unary(
        &mut self,
        ctx: &mut FunctionCtx,
        op: crate::parser::ast::UnaryOp,
        operand: &Expr,
        result_type: &Type,
    ) -> Result<String, String> {
        use crate::parser::ast::UnaryOp;
        match op {
            UnaryOp::Neg => {
                if let ExprKind::Int(value) = &operand.kind {
                    return Ok(format!("-{value}"));
                }
                let value = self.gen_expr(ctx, operand)?;
                let llvm_type = self.llvm_type(result_type)?;
                if result_type.is_float() {
                    let temp = ctx.temp();
                    ctx.emit(format!("{temp} = fneg {llvm_type} {value}"));
                    Ok(temp)
                } else {
                    let temp = ctx.temp();
                    ctx.emit(format!("{temp} = sub {llvm_type} 0, {value}"));
                    Ok(temp)
                }
            }
            UnaryOp::Not => {
                let value = self.gen_expr(ctx, operand)?;
                let temp = ctx.temp();
                ctx.emit(format!("{temp} = xor i1 {value}, true"));
                Ok(temp)
            }
        }
    }

    fn gen_binary(
        &mut self,
        ctx: &mut FunctionCtx,
        left: &Expr,
        op: BinaryOp,
        right: &Expr,
    ) -> Result<String, String> {
        let left_value = self.gen_expr(ctx, left)?;
        let right_value = self.gen_expr(ctx, right)?;
        let operand_type = &left.ty;
        let llvm_type = self.llvm_type(operand_type)?;
        let float = operand_type.is_float();
        let temp = ctx.temp();

        match op {
            BinaryOp::Add | BinaryOp::Sub | BinaryOp::Mul | BinaryOp::Div | BinaryOp::Rem => {
                let instruction = match (op, float) {
                    (BinaryOp::Add, false) => "add",
                    (BinaryOp::Add, true) => "fadd",
                    (BinaryOp::Sub, false) => "sub",
                    (BinaryOp::Sub, true) => "fsub",
                    (BinaryOp::Mul, false) => "mul",
                    (BinaryOp::Mul, true) => "fmul",
                    (BinaryOp::Div, false) => {
                        if operand_type.is_signed_integer() {
                            "sdiv"
                        } else {
                            "udiv"
                        }
                    }
                    (BinaryOp::Div, true) => "fdiv",
                    (BinaryOp::Rem, false) => {
                        if operand_type.is_signed_integer() {
                            "srem"
                        } else {
                            "urem"
                        }
                    }
                    (BinaryOp::Rem, true) => "frem",
                    _ => unreachable!(),
                };
                ctx.emit(format!(
                    "{temp} = {instruction} {llvm_type} {left_value}, {right_value}"
                ));
                Ok(temp)
            }
            BinaryOp::Eq
            | BinaryOp::Ne
            | BinaryOp::Lt
            | BinaryOp::Le
            | BinaryOp::Gt
            | BinaryOp::Ge => {
                if float {
                    let predicate = match op {
                        BinaryOp::Eq => "oeq",
                        BinaryOp::Ne => "one",
                        BinaryOp::Lt => "olt",
                        BinaryOp::Le => "ole",
                        BinaryOp::Gt => "ogt",
                        BinaryOp::Ge => "oge",
                        _ => unreachable!(),
                    };
                    ctx.emit(format!(
                        "{temp} = fcmp {predicate} {llvm_type} {left_value}, {right_value}"
                    ));
                } else {
                    let predicate = match op {
                        BinaryOp::Eq => "eq",
                        BinaryOp::Ne => "ne",
                        BinaryOp::Lt => {
                            if operand_type.is_signed_integer() {
                                "slt"
                            } else {
                                "ult"
                            }
                        }
                        BinaryOp::Le => {
                            if operand_type.is_signed_integer() {
                                "sle"
                            } else {
                                "ule"
                            }
                        }
                        BinaryOp::Gt => {
                            if operand_type.is_signed_integer() {
                                "sgt"
                            } else {
                                "ugt"
                            }
                        }
                        BinaryOp::Ge => {
                            if operand_type.is_signed_integer() {
                                "sge"
                            } else {
                                "uge"
                            }
                        }
                        _ => unreachable!(),
                    };
                    ctx.emit(format!(
                        "{temp} = icmp {predicate} {llvm_type} {left_value}, {right_value}"
                    ));
                }
                Ok(temp)
            }
            BinaryOp::BitAnd
            | BinaryOp::BitOr
            | BinaryOp::BitXor
            | BinaryOp::Shl
            | BinaryOp::Shr => {
                let instruction = match op {
                    BinaryOp::BitAnd => "and",
                    BinaryOp::BitOr => "or",
                    BinaryOp::BitXor => "xor",
                    BinaryOp::Shl => "shl",
                    BinaryOp::Shr => {
                        if operand_type.is_signed_integer() {
                            "ashr"
                        } else {
                            "lshr"
                        }
                    }
                    _ => unreachable!(),
                };
                ctx.emit(format!(
                    "{temp} = {instruction} {llvm_type} {left_value}, {right_value}"
                ));
                Ok(temp)
            }
            BinaryOp::And | BinaryOp::Or => unreachable!(),
        }
    }

    fn gen_logical(
        &mut self,
        ctx: &mut FunctionCtx,
        left: &Expr,
        op: BinaryOp,
        right: &Expr,
    ) -> Result<String, String> {
        let left_value = self.gen_expr(ctx, left)?;
        let right_label = ctx.label();
        let short_label = ctx.label();
        let merge_label = ctx.label();

        if matches!(op, BinaryOp::And) {
            ctx.terminate(format!(
                "br i1 {left_value}, label %{right_label}, label %{short_label}"
            ));
        } else {
            ctx.terminate(format!(
                "br i1 {left_value}, label %{short_label}, label %{right_label}"
            ));
        }

        ctx.start_label(&right_label);
        let right_value = self.gen_expr(ctx, right)?;
        let right_end = ctx.current_label.clone();
        if !ctx.terminated {
            ctx.terminate(format!("br label %{merge_label}"));
        }

        ctx.start_label(&short_label);
        let short_end = ctx.current_label.clone();
        ctx.terminate(format!("br label %{merge_label}"));

        ctx.start_label(&merge_label);
        let temp = ctx.temp();
        let short_value = if matches!(op, BinaryOp::And) {
            "false"
        } else {
            "true"
        };
        ctx.emit(format!(
            "{temp} = phi i1 [ {short_value}, %{short_end} ], [ {right_value}, %{right_end} ]"
        ));
        Ok(temp)
    }

    fn emit_globals(&self) -> String {
        let mut output = String::new();
        let formats = [
            (".kern.bool.true", "true"),
            (".kern.bool.false", "false"),
            (".kern.scan.i8", "%hhd"),
            (".kern.scan.i16", "%hd"),
            (".kern.scan.i32", "%d"),
            (".kern.scan.i64", "%lld"),
            (".kern.scan.isize", "%ld"),
            (".kern.scan.u8", "%hhu"),
            (".kern.scan.u16", "%hu"),
            (".kern.scan.u32", "%u"),
            (".kern.scan.u64", "%llu"),
            (".kern.scan.usize", "%lu"),
            (".kern.scan.f32", "%f"),
            (".kern.scan.f64", "%lf"),
            (".kern.scan.char", " %c"),
        ];
        for (name, text) in formats {
            let bytes = text.as_bytes();
            let _ = writeln!(
                output,
                "@{name} = private unnamed_addr constant [{} x i8] {}",
                bytes.len() + 1,
                llvm_c_string(bytes)
            );
        }
        for (index, bytes) in self.strings.iter().enumerate() {
            let _ = writeln!(
                output,
                "@.kern.str.{index} = private unnamed_addr constant [{} x i8] {}",
                bytes.len() + 1,
                llvm_c_string(bytes)
            );
        }
        output
    }
}

fn integer_format(radix: crate::parser::ast::Radix, length: &str) -> String {
    let conversion = match radix {
        crate::parser::ast::Radix::HexLower => "x",
        crate::parser::ast::Radix::HexUpper => "X",
        crate::parser::ast::Radix::Octal => "o",
        crate::parser::ast::Radix::Binary => unreachable!(),
    };
    format!("{length}{conversion}")
}

fn binary_print_helper() -> String {
    [
        "define void @kern.print.binary(i64 %value, i32 %width) {",
        "entry:",
        "  %index.addr = alloca i32",
        "  %started.addr = alloca i1",
        "  %last = sub i32 %width, 1",
        "  store i32 %last, ptr %index.addr",
        "  store i1 false, ptr %started.addr",
        "  br label %loop",
        "loop:",
        "  %index = load i32, ptr %index.addr",
        "  %active = icmp sge i32 %index, 0",
        "  br i1 %active, label %bit, label %finish",
        "bit:",
        "  %shift = zext i32 %index to i64",
        "  %shifted = lshr i64 %value, %shift",
        "  %bit.value = and i64 %shifted, 1",
        "  %nonzero = icmp ne i64 %bit.value, 0",
        "  %started = load i1, ptr %started.addr",
        "  %emit = or i1 %started, %nonzero",
        "  br i1 %emit, label %write, label %step",
        "write:",
        "  %digit = trunc i64 %bit.value to i32",
        "  %character = add i32 %digit, 48",
        "  %ignored = call i32 @putchar(i32 %character)",
        "  store i1 true, ptr %started.addr",
        "  br label %step",
        "step:",
        "  %next = sub i32 %index, 1",
        "  store i32 %next, ptr %index.addr",
        "  br label %loop",
        "finish:",
        "  %printed = load i1, ptr %started.addr",
        "  br i1 %printed, label %done, label %zero",
        "zero:",
        "  %zero.ignored = call i32 @putchar(i32 48)",
        "  br label %done",
        "done:",
        "  ret void",
        "}",
    ]
    .join("\n")
}

fn float_constant(value: f64, ty: &Type) -> String {
    let bits = if matches!(ty, Type::F32) {
        (value as f32) as f64
    } else {
        value
    };
    format!("0x{:016X}", bits.to_bits())
}

fn llvm_c_string(bytes: &[u8]) -> String {
    let mut output = String::from("c\"");
    for byte in bytes.iter().copied().chain(std::iter::once(0)) {
        let _ = write!(output, "\\{byte:02X}");
    }
    output.push('"');
    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lexer::lex;
    use crate::parser::parse;
    use crate::semantic::analyze;

    fn generate_source(source: &str) -> Result<String, String> {
        let tokens = lex(source).tokens;
        let parsed = parse(tokens);
        let analyzed = analyze(parsed.program);
        assert!(
            !analyzed
                .diagnostics
                .iter()
                .any(|diagnostic| diagnostic.is_error()),
            "{:?}",
            analyzed.diagnostics
        );
        generate(&analyzed.program)
    }

    #[test]
    fn emits_arithmetic_and_main() {
        let ir = generate_source(
            r#"
            fn add(a: i32, b: i32) -> i32 { return a + b; }
            fn main() { let x = add(10, 20); print(x); }
        "#,
        )
        .unwrap();
        assert!(ir.contains("define i32 @main()"));
        assert!(ir.contains("define i32 @kern.add(i32 %p0, i32 %p1)"));
        assert!(ir.contains("add i32"));
        assert!(ir.contains("@printf"));
    }

    #[test]
    fn emits_control_flow_and_structs() {
        let ir = generate_source(
            r#"
            struct Pair { left: i32, right: i32 }
            fn main() {
                let pair = Pair { left: 1, right: 2 };
                let mut i = 0;
                while i < pair.right { i = i + 1; }
                if i == 2 { print(pair.left); }
                for (let mut j = 0; j < 2; j = j + 1) { print(j); }
            }
        "#,
        )
        .unwrap();
        assert!(ir.contains("%kern.Pair = type { i32, i32 }"));
        assert!(ir.contains("insertvalue"));
        assert!(ir.contains("extractvalue"));
        assert!(ir.contains("icmp slt"));
    }

    #[test]
    fn emits_float_and_bool_printing() {
        let ir = generate_source(
            r#"
            fn main() {
                let x: f64 = 1.5;
                print(x);
                print(true);
            }
        "#,
        )
        .unwrap();
        assert!(ir.contains("double 0x3FF8000000000000"));
        assert!(ir.contains("select i1"));
    }
}
